/**
 * Get translation for a key
 * @param {string} language - Language code (en, fr, es, de, pt)
 * @param {string} key - Translation key (e.g., "home.welcome")
 * @param {string} defaultValue - Default value if translation not found
 */
export function getTranslation(language = defaultLanguage, key, defaultValue = key) {
  const keys = key.split(".");
  let value = translations[language] || translations[defaultLanguage];

  for (const k of keys) {
    value = value?.[k];
    if (!value) return defaultValue;
  }

  return value || defaultValue;
}

/**
 * Get all translations for a language
 */
export function getLanguageTranslations(language = defaultLanguage) {
  return translations[language] || translations[defaultLanguage];
}
